"""AI quiz orchestration with a safe, always-available offline fallback.

A live provider is optional. When configured, the server calls an
OpenAI-compatible Chat Completions endpoint, strictly validates the returned
JSON, and never exposes the API key or answers to the browser. Any provider or
validation failure falls back to the local question generator.
"""

from __future__ import annotations

import json
import logging
import random
import re
import secrets
import urllib.error
import urllib.request
from dataclasses import dataclass, field

from .question_bank import _clean, _prompt_key, generate_offline_questions, supported_topics


logger = logging.getLogger(__name__)


def _config_value(config, key, default=None):
    """Read from a Flask config mapping, a plain dict, or a config class."""
    if hasattr(config, "get"):
        return config.get(key, default)
    return getattr(config, key, default)

SYSTEM_PROMPT = """You are a careful Python programming tutor creating fresh multiple-choice practice.
Return ONLY one JSON object, with no markdown, code fences, commentary, or extra keys.

The JSON object must have this shape:
{"questions":[{"prompt":"...","options":["...","...","...","..."],"answer":"exact option text","explanation":"...","skill":"...","difficulty":"foundation|core|stretch"}]}

Rules:
- Produce exactly the requested number of distinct questions for the requested topic.
- Every question has exactly four distinct, plausible string options.
- Exactly one option is correct; `answer` must exactly equal one of the option strings.
- Use valid Python 3 code in code-tracing prompts. Include `\\n` for line breaks and spaces for indentation.
- The correct answer must be unambiguous. Do not use "all of the above" or option letters as answers.
- `explanation` teaches why the answer is correct in one or two sentences.
- `skill` is a short concept label; `difficulty` is one of foundation, core, or stretch.
- Do not repeat any prompt in `avoid_prompts`. Use the supplied session nonce to vary numbers, names, and contexts.
- Prefer the requested difficulty mix, and include a short code-tracing question where appropriate.
- Do not include hidden solutions, metadata, or any text outside the JSON object.
"""


class AIQuizGenerationError(RuntimeError):
    """Raised when a live provider returns unusable quiz content."""


@dataclass
class GenerationResult:
    questions: list
    provider: str
    model: str
    requested_difficulty: str
    effective_difficulty: str
    seed: str
    warning: str = ""
    live: bool = False
    extras: dict = field(default_factory=dict)

    @property
    def label(self):
        if self.provider == "live_ai":
            return f"Live AI · {self.model}"
        if self.provider == "offline_fallback":
            return "Offline AI generator (fallback)"
        return "Offline AI generator"


def provider_status(config):
    """Return a truthful, user-facing description of the active AI mode."""
    api_key = str(_config_value(config, "AI_API_KEY", "") or "").strip()
    model = str(_config_value(config, "AI_MODEL", "gpt-4o-mini") or "gpt-4o-mini").strip()
    if api_key:
        return {
            "live": True,
            "label": "Live AI ready",
            "model": model,
            "description": "Fresh questions are generated by your configured model. If the provider is unavailable, the offline generator takes over automatically.",
            "topics": supported_topics(),
        }
    return {
        "live": False,
        "label": "Offline AI generator active",
        "model": "local-question-engine-v1",
        "description": "The app works without an API key. This mode is a validated template generator, not a large language model; add AI_API_KEY for live LLM questions.",
        "topics": supported_topics(),
    }


def choose_difficulty(mastery, requested="adaptive"):
    """Map a learner's mastery estimate to a transparent practice tier."""
    if requested in ("foundation", "core", "stretch"):
        return requested
    mastery = max(0.0, min(1.0, float(mastery or 0.0)))
    if mastery < 0.40:
        return "foundation"
    if mastery < 0.70:
        return "core"
    return "stretch"


def difficulty_reason(mastery, requested, effective):
    if requested in ("foundation", "core", "stretch"):
        return f"You chose {effective} difficulty for this session."
    return (f"Adaptive mode selected {effective} questions because your current "
            f"estimated mastery is {mastery:.0%}.")


def _extract_json(text):
    """Parse a JSON object even if a model wraps it in a code fence."""
    if not isinstance(text, str) or not text.strip():
        raise AIQuizGenerationError("empty provider response")
    cleaned = text.strip()
    cleaned = re.sub(r"^```(?:json)?\s*", "", cleaned, flags=re.IGNORECASE)
    cleaned = re.sub(r"\s*```$", "", cleaned)
    try:
        return json.loads(cleaned)
    except json.JSONDecodeError:
        start = cleaned.find("{")
        if start < 0:
            raise AIQuizGenerationError("provider response is not JSON")
        try:
            payload, _ = json.JSONDecoder().raw_decode(cleaned[start:])
            return payload
        except json.JSONDecodeError as exc:
            raise AIQuizGenerationError("provider response contains invalid JSON") from exc


def _validate_live_questions(payload, count, topic, difficulty, rng, avoid_prompts):
    if not isinstance(payload, dict) or not isinstance(payload.get("questions"), list):
        raise AIQuizGenerationError("provider response has no questions list")
    raw_questions = payload["questions"]
    if len(raw_questions) != count:
        raise AIQuizGenerationError("provider returned the wrong number of questions")
    avoid = {_prompt_key(item) for item in (avoid_prompts or [])}
    seen = set()
    questions = []
    valid_tiers = {"foundation", "core", "stretch"}
    for raw in raw_questions:
        if not isinstance(raw, dict):
            raise AIQuizGenerationError("provider returned a non-object question")
        prompt = _clean(raw.get("prompt"), 600)
        raw_options = raw.get("options")
        if not isinstance(raw_options, list):
            raise AIQuizGenerationError("provider returned a non-list options field")
        options = [_clean(item, 180) for item in raw_options if _clean(item, 180)]
        answer = _clean(raw.get("answer"), 180)
        explanation = _clean(raw.get("explanation"), 600)
        skill = _clean(raw.get("skill") or "Python concept", 80)
        tier = raw.get("difficulty")
        tier = tier if tier in valid_tiers else difficulty
        if len(prompt) < 12 or len(explanation) < 12:
            raise AIQuizGenerationError("provider returned an incomplete question")
        if len(options) != 4 or len(set(options)) != 4:
            raise AIQuizGenerationError("provider returned invalid options")
        if answer not in options:
            index = raw.get("correct_index")
            if isinstance(index, int) and 0 <= index < len(options):
                answer = options[index]
            else:
                raise AIQuizGenerationError("provider answer is not one of its options")
        key = _prompt_key(prompt)
        if key in seen or key in avoid:
            raise AIQuizGenerationError("provider returned a duplicate or recent prompt")
        seen.add(key)
        rng.shuffle(options)
        questions.append({
            "prompt": prompt,
            "options": options,
            "answer": answer,
            "explanation": explanation,
            "skill": skill,
            "difficulty": tier,
            "topic": topic,
            "source": "live_ai",
        })
    return questions


def _call_live_ai(config, topic, count, difficulty, mastery, recent_score,
                  recent_prompts, nonce, rng):
    api_key = str(_config_value(config, "AI_API_KEY", "") or "").strip()
    base = str(_config_value(config, "AI_API_BASE", "https://api.openai.com/v1") or "").rstrip("/")
    model = str(_config_value(config, "AI_MODEL", "gpt-4o-mini") or "gpt-4o-mini").strip()
    if not api_key or not base.startswith(("http://", "https://")):
        raise AIQuizGenerationError("live AI is not configured")
    try:
        timeout = max(5, min(90, int(_config_value(config, "AI_TIMEOUT", 25) or 25)))
    except (TypeError, ValueError):
        timeout = 25
    user_payload = {
        "topic": topic,
        "question_count": count,
        "requested_difficulty": difficulty,
        "estimated_mastery": round(float(mastery or 0.0), 4),
        "latest_quiz_score": None if recent_score is None else round(float(recent_score), 4),
        "session_nonce": nonce,
        "avoid_prompts": [_clean(item, 180) for item in (recent_prompts or [])[:20]],
    }
    body = {
        "model": model,
        "temperature": 0.9,
        "max_tokens": 4200,
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": json.dumps(user_payload, ensure_ascii=False)},
        ],
    }
    request = urllib.request.Request(
        base + "/chat/completions",
        data=json.dumps(body).encode("utf-8"),
        headers={
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
            "Accept": "application/json",
        },
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            raw = response.read().decode("utf-8", errors="replace")
    except urllib.error.HTTPError as exc:
        raise AIQuizGenerationError(f"provider returned HTTP {exc.code}") from exc
    except (urllib.error.URLError, TimeoutError, OSError) as exc:
        raise AIQuizGenerationError("provider connection failed") from exc
    try:
        response_payload = json.loads(raw)
        message = response_payload["choices"][0]["message"]["content"]
        if isinstance(message, list):
            message = "".join(part.get("text", "") for part in message if isinstance(part, dict))
    except (json.JSONDecodeError, KeyError, IndexError, TypeError) as exc:
        raise AIQuizGenerationError("provider response has an unexpected shape") from exc
    payload = _extract_json(message)
    return _validate_live_questions(payload, count, topic, difficulty, rng, recent_prompts)


def generate_quiz(config, topic, count=10, difficulty="adaptive", mastery=0.0,
                  recent_score=None, recent_prompts=None):
    """Create a fresh quiz, preferring live AI and always validating output."""
    try:
        count = max(1, min(20, int(count)))
    except (TypeError, ValueError):
        count = 10
    effective = choose_difficulty(mastery, difficulty)
    nonce = secrets.token_hex(10)
    rng = random.Random(int(nonce, 16))
    live_configured = bool(str(_config_value(config, "AI_API_KEY", "") or "").strip())
    warning = ""

    if live_configured:
        try:
            questions = _call_live_ai(config, topic, count, effective, mastery,
                                      recent_score, recent_prompts, nonce, rng)
            return GenerationResult(
                questions=questions, provider="live_ai",
                model=str(_config_value(config, "AI_MODEL", "gpt-4o-mini")),
                requested_difficulty=difficulty, effective_difficulty=effective,
                seed=nonce, live=True,
                extras={"avoided_recent_prompts": len(recent_prompts or [])},
            )
        except Exception as exc:  # noqa: BLE001 - any provider failure must fall back.
            logger.warning("Live AI quiz generation failed (%s); using offline generator.",
                           type(exc).__name__)
            warning = ("Live AI was unavailable or returned invalid questions, "
                       "so this quiz used the offline generator.")

    questions = generate_offline_questions(
        topic, count=count, difficulty=effective, rng=rng,
        avoid_prompts=recent_prompts,
    )
    return GenerationResult(
        questions=questions,
        provider="offline_fallback" if live_configured else "offline_generator",
        model="local-question-engine-v1",
        requested_difficulty=difficulty,
        effective_difficulty=effective,
        seed=nonce,
        warning=warning,
        extras={"avoided_recent_prompts": len(recent_prompts or [])},
    )
